const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const { pathToFileURL } = require('node:url');
const { once } = require('node:events');
const { existsSync, mkdtempSync } = require('node:fs');
const { resolve, join } = require('node:path');
const { tmpdir } = require('node:os');
const { chromium } = require('playwright');
const beRoot = resolve(__dirname, '../../GoMate-BE');
const beRequire = createRequire(beRoot + '/package.json');
const be = name => import(pathToFileURL(beRoot + '/src/' + name + '.js').href);

(async () => {
  const { MongoMemoryServer } = beRequire('mongodb-memory-server');
  const [{ createApp }, { readConfig }, { createClient, initializeDatabase }, { createAuthRepository }] = await Promise.all(['app', 'config/env', 'database/mongo', 'modules/auth/repository'].map(be));
  const mongo = await MongoMemoryServer.create();
  const client = createClient(readConfig({ MONGODB_URI: mongo.getUri('portal_registration') }));
  let server, browser;
  const artifacts = mkdtempSync(join(tmpdir(), 'gomate-portal-registration-'));
  try {
    await client.connect(); const db = client.db(); await initializeDatabase(db);
    let verificationCode;
    server = createApp(readConfig({}), {
      authRepository: createAuthRepository(db),
      verificationMailer: { assertConfigured() {}, async sendCode(email, code) { verificationCode = code; } },
    }).listen(0, '127.0.0.1');
    await once(server, 'listening');
    const base = `http://127.0.0.1:${server.address().port}`;
    browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || (existsSync('C:/Program Files/Google/Chrome/Application/chrome.exe') ? 'C:/Program Files/Google/Chrome/Application/chrome.exe' : undefined), headless: true });
    const page = await browser.newPage({ viewport: { width: 1360, height: 1050 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/portal');
    await page.getByRole('heading', { name: 'Đăng nhập portal', exact: true }).waitFor();
    const signup = page.getByRole('button', { name: 'Đăng ký tài khoản doanh nghiệp', exact: true });
    assert.ok((await signup.boundingBox()).y < (await page.getByRole('link', { name: 'Khám phá bản demo' }).boundingBox()).y);
    assert.ok(await page.getByRole('img', { name: 'GoMate' }).count() || await page.locator('[aria-label="GoMate"]').count());
    await page.screenshot({ path: join(artifacts, 'login-desktop.png'), fullPage: true });
    await signup.click();
    await page.getByLabel('Tên người đại diện', { exact: true }).fill('Đại diện doanh nghiệp');
    await page.getByLabel('Email', { exact: true }).fill('partner@example.com');
    await page.getByLabel('Mật khẩu', { exact: true }).fill('Secure123!');
    await page.getByLabel('Xác nhận mật khẩu', { exact: true }).fill('Mismatch123!');
    await page.getByRole('button', { name: 'Tạo tài khoản doanh nghiệp', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Mật khẩu xác nhận chưa khớp.' }).waitFor();
    assert.equal(await db.collection('users').countDocuments({ email: 'partner@example.com' }), 0);
    await page.getByLabel('Xác nhận mật khẩu', { exact: true }).fill('Secure123!');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: join(artifacts, 'register-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: 'Tạo tài khoản doanh nghiệp', exact: true }).click();
    await page.getByRole('heading', { name: 'Xác minh email', exact: true }).waitFor();
    const user = await db.collection('users').findOne({ email: 'partner@example.com' });
    assert.ok(user); assert.notEqual(user.role, 'business'); assert.notEqual(user.email_verified, true);
    assert.match(verificationCode, /^\d{6}$/);
    await page.getByLabel('Mã xác minh', { exact: true }).fill(verificationCode === '000000' ? '111111' : '000000');
    await page.getByRole('button', { name: 'Xác minh và tiếp tục', exact: true }).click();
    await page.getByRole('alert').waitFor();
    await page.getByLabel('Mã xác minh', { exact: true }).fill(verificationCode);
    await page.getByRole('button', { name: 'Xác minh và tiếp tục', exact: true }).click();
    await page.getByRole('heading', { name: 'Xác minh doanh nghiệp', exact: true }).waitFor();
    assert.equal((await db.collection('users').findOne({ id: user.id })).email_verified, true);
    assert.equal(await db.collection('business_applications').countDocuments({ ownerId: user.id }), 0);
    await page.reload();
    await page.getByRole('heading', { name: 'Xác minh doanh nghiệp', exact: true }).waitFor();
    assert.equal(await page.getByRole('link', { name: 'Hướng dẫn demo', exact: true }).count(), 0);
    await page.getByRole('radio', { name: 'Cá nhân', exact: true }).check();
    await page.getByLabel('Ngành', { exact: true }).selectOption('Khác');
    assert.ok(await page.getByLabel('Ngành', { exact: true }).locator('option').count() > 20);
    for (const [label, value] of [['Tên doanh nghiệp', 'HỘ KINH DOANH THỬ NGHIỆM'], ['Số giấy chứng nhận', 'HKD-123456'], ['Địa chỉ chi tiết', '12 Test Street'], ['Họ và tên người đại diện', 'Người đại diện'], ['Chức vụ', 'Chủ hộ kinh doanh'], ['Email liên hệ', 'partner@example.com'], ['Số điện thoại', '0901234567']]) await page.getByLabel(label, { exact: true }).fill(value);
    const { PDFDocument } = beRequire('pdf-lib'); const pdf = await PDFDocument.create(); pdf.addPage(); const buffer = Buffer.from(await pdf.save());
    await page.getByLabel('Hồ sơ xác minh', { exact: true }).setInputFiles({ name: 'household-license.pdf', mimeType: 'application/pdf', buffer });
    await page.getByLabel('Tài liệu bổ sung (không bắt buộc)', { exact: true }).setInputFiles({ name: 'extra.pdf', mimeType: 'application/pdf', buffer });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: join(artifacts, 'verification-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1360, height: 1050 });
    await page.screenshot({ path: join(artifacts, 'verification-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Gửi hồ sơ xác minh', exact: true }).click();
    await page.getByText('Chờ duyệt', { exact: true }).waitFor();
    await page.reload(); await page.getByText('HKD-123456', { exact: true }).waitFor();
    const application = await db.collection('business_applications').findOne({ ownerId: user.id });
    assert.equal(application.accountType, 'individual'); assert.equal(application.country, 'VN'); assert.equal(application.category, 'Khác'); assert.equal(application.supplementalLicense.name, 'extra.pdf');
    await page.addInitScript(() => {
      window.__authFormFlashed = false;
      new MutationObserver(() => { if (document.querySelector('.gm-auth-form input[type="password"]')) window.__authFormFlashed = true; }).observe(document, { childList: true, subtree: true });
    });
    let releaseProfile;
    const profileGate = new Promise(resolve => { releaseProfile = resolve; });
    await page.route('**/api/portal/me', async route => { await profileGate; await route.continue(); });
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByRole('status').filter({ hasText: 'Đang tải không gian làm việc' }).waitFor();
    assert.equal(await page.locator('input[type="password"]').count(), 0);
    releaseProfile();
    await page.getByText('HKD-123456', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.__authFormFlashed), false);
    await page.unroute('**/api/portal/me');
    await page.route('**/api/portal/me', route => route.fulfill({ status: 503, json: { error: 'Workspace temporarily unavailable' } }));
    await page.reload();
    await page.getByRole('alert').filter({ hasText: 'Workspace temporarily unavailable' }).waitFor();
    assert.equal(await page.evaluate(() => window.__authFormFlashed), false);
    assert.ok(await page.evaluate(() => localStorage.getItem('gomate.session')));
    await page.unroute('**/api/portal/me');
    await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
    await page.getByText('HKD-123456', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.__authFormFlashed), false);
    await page.route('**/api/portal/me', route => route.fulfill({ status: 401, json: { error: 'Session expired' } }));
    await page.reload();
    await page.getByRole('heading', { name: 'Đăng nhập portal', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => localStorage.getItem('gomate.session')), null);
    await page.unroute('**/api/portal/me');
    await page.goto(base + '/demo');
    await page.getByRole('heading', { name: 'Linh · Admin', exact: true }).waitFor();
    assert.equal(await page.getByText('demo.staff@gomate.local', { exact: true }).count(), 0);
    console.log('PASS reload never mounts a login form during profile restoration or retry; expired sessions show login; demo offers Admin.');
    assert.deepEqual(errors, []);
    console.log('PASS real registration, password confirmation, email verification, pending business onboarding, session reload and mobile layout. Artifacts:', artifacts);
  } finally {
    await browser?.close(); if (server) await new Promise(resolve => server.close(resolve));
    await client.close(); await mongo.stop();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
